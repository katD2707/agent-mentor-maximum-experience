import { existsSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

// src/vendor/mentor-mascot.* are copies of packages/mentor-mascot (owner M) made by scripts/sync-mascot.mjs
// (run by predev/prebuild). Fails when M changed the source and nobody re-ran the sync: `pnpm sync:mascot`.
const pairs: [string, string][] = [
  ["../../../../packages/mentor-mascot/mascot.js", "../vendor/mentor-mascot.js"],
  ["../../../../packages/mentor-mascot/mascot.d.ts", "../vendor/mentor-mascot.d.ts"],
];

describe("vendored <mentor-mascot>", () => {
  for (const [src, dst] of pairs) {
    const srcPath = fileURLToPath(new URL(src, import.meta.url));
    const dstPath = fileURLToPath(new URL(dst, import.meta.url));
    it.skipIf(!existsSync(srcPath))(`${dst.split("/").pop()} matches the package source`, () => {
      const vendored = readFileSync(dstPath, "utf8");
      expect(vendored.startsWith("// GENERATED by apps/web/scripts/sync-mascot.mjs")).toBe(true);
      expect(vendored.slice(vendored.indexOf("\n") + 1)).toBe(readFileSync(srcPath, "utf8"));
    });
  }
});
